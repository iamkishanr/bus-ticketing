import Link from "next/link";
import { redirect } from "next/navigation";
import { hasRole } from "@/lib/auth";
import Mast from "@/components/Mast";
import AdminNav from "@/components/AdminNav";
import { serviceOverview, totals, topSegments } from "@/lib/crowd/overview";
import { CROWD_COPY, crowdLevel } from "@/lib/crowd/estimate";
import { prisma } from "@/lib/db";

export const dynamic = "force-dynamic";

const DAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];

export default async function OverviewPage() {
  if (!hasRole("admin")) redirect("/admin");

  const services = await serviceOverview();
  const t = await totals(services);
  const segments = await topSegments();

  // Seeded demo traffic is labelled, so the monitor can say when its figures
  // are not real boardings.
  const seeded = await prisma.booking.count({ where: { paymentProviderRef: "sim_seed" } });
  const real = await prisma.booking.count({ where: { paymentProviderRef: { not: "sim_seed" } } });

  if (services.length === 0) {
    return (
      <main className="shell shell--wide">
        <Mast label="Monitor" />
        <AdminNav current="monitor" />
        <h1>Nothing to monitor yet</h1>
        <p className="lede">
          Occupancy appears here once passengers start boarding. Every validated scan
          feeds this page — no separate tracking is needed.
        </p>
      </main>
    );
  }

  return (
    <main className="shell shell--wide">
      <Mast label="Monitor" />
      <AdminNav current="monitor" />
      <h1>How full are the buses?</h1>
      <p className="lede">
        Every figure here is counted from validated boarding scans — the same scans the
        conductor makes at the door.
      </p>

      {seeded > 0 && (
        <div className="notice notice--info">
          <strong>Includes demo data.</strong> {seeded.toLocaleString("en-IN")} of these
          boardings were generated by the seed to populate this page
          {real > 0 && <>, alongside {real.toLocaleString("en-IN")} real booking{real === 1 ? "" : "s"}</>}.
          Clear them with <strong>Reset demo data</strong> under Services &amp; trips.
        </div>
      )}

      <div className="card">
        <div className="stats">
          <div>
            <div className="stat__n">{t.boardings.toLocaleString("en-IN")}</div>
            <div className="stat__k">Passengers boarded</div>
          </div>
          <div>
            <div className="stat__n">{t.tripsRun}</div>
            <div className="stat__k">Trips run</div>
          </div>
          <div>
            <div className="stat__n">{t.avgPct}%</div>
            <div className="stat__k">Average occupancy</div>
          </div>
          <div>
            <div className="stat__n">{t.servicesTracked}</div>
            <div className="stat__k">Services tracked</div>
          </div>
        </div>
      </div>

      <h2>Occupancy by service</h2>
      <div className="card">
        <div className="heatkey">
          <span><i className="heatkey__box heatkey__box--quiet" /> Quiet</span>
          <span><i className="heatkey__box heatkey__box--seats" /> Seats usually free</span>
          <span><i className="heatkey__box heatkey__box--full" /> Usually busy</span>
          <span className="muted">Peak is the fullest single trip recorded.</span>
        </div>
        <div className="scroller">
          <table>
            <thead>
              <tr>
                <th>Departs</th>
                <th>Route</th>
                <th>Trips</th>
                <th>Avg riders</th>
                <th>Average load</th>
                <th>Peak</th>
              </tr>
            </thead>
            <tbody>
              {services.map((s) => (
                <tr key={s.scheduleId}>
                  <td className="mono">{s.departureTime}</td>
                  <td className="wrap">
                    {s.routeName}
                    <div className="muted">{s.busLabel}</div>
                  </td>
                  <td className="mono">{s.tripsRun}</td>
                  <td className="mono">{s.avgBoarded} / {s.capacity}</td>
                  <td>
                    <div className="loadbar" title={`${s.avgPct}% average`}>
                      <div className={`loadbar__fill loadbar__fill--${s.level}`} style={{ width: `${s.avgPct}%` }} />
                      <span className="loadbar__pct mono">{s.avgPct}%</span>
                    </div>
                    <div className={`muted crowd--${s.level}`} style={{ fontSize: "0.76rem" }}>
                      {CROWD_COPY[s.level]}
                    </div>
                  </td>
                  <td className="mono">{s.peakPct}%</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      <h2>Load by day of week</h2>
      <div className="card">
        <p className="muted" style={{ marginTop: 0 }}>
          Average occupancy per service, as a percentage of seats. Same bands the
          passenger site uses.
        </p>
        <div className="heatkey">
          <span><i className="heatkey__box heatkey__box--quiet" /> Under 40% — quiet</span>
          <span><i className="heatkey__box heatkey__box--seats" /> 40–79% — seats usually free</span>
          <span><i className="heatkey__box heatkey__box--full" /> 80% and over — usually busy</span>
          <span><i className="heatkey__box heatkey__box--none" /> Does not run</span>
        </div>
        <div className="scroller">
          <table className="heat">
            <thead>
              <tr>
                <th>Service</th>
                {DAYS.map((d) => <th key={d} style={{ textAlign: "center" }}>{d}</th>)}
              </tr>
            </thead>
            <tbody>
              {services.map((s) => (
                <tr key={s.scheduleId}>
                  <td className="wrap">
                    <span className="mono">{s.departureTime}</span>{" "}
                    <span className="muted">{s.routeName.replace(/ —.*/, "")}</span>
                  </td>
                  {s.byWeekday.map((w) => (
                    <td key={w.weekday} className="heat__cell">
                      {w.pct === null ? (
                        <span className="heat__none" title="Does not run">·</span>
                      ) : (
                        <span
                          className={`heat__box heat__box--${crowdLevel(w.pct)} mono`}
                          title={`${w.pct}% of seats taken on average`}
                        >
                          {w.pct}%
                        </span>
                      )}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {segments.length > 0 && (
        <>
          <h2>Busiest segments</h2>
          <div className="card">
            <div className="scroller">
              <table>
                <thead><tr><th>From</th><th>To</th><th>Passengers</th></tr></thead>
                <tbody>
                  {segments.map((sg, i) => (
                    <tr key={i}>
                      <td className="wrap">{sg.origin}</td>
                      <td className="wrap">{sg.destination}</td>
                      <td className="mono">{Number(sg.riders).toLocaleString("en-IN")}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <p className="muted" style={{ marginBottom: 0 }}>
              Boarding and alighting stops come from each booking, so this counts intended
              journeys rather than verified exits.
            </p>
          </div>
        </>
      )}

    </main>
  );
}
